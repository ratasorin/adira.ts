/** Emit headless operand parsers and a separate optional dashboard adapter. */
import {
  ReadResource,
  type ResourceLike,
  type ScalarDefinition,
} from "@n/adira.core.ts";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { format } from "prettier";
import * as contracts from "../contracts/resources";

const q = (value: string) => JSON.stringify(value);
interface Entry {
  name: string;
  resource: ResourceLike;
  expression: string;
}
const entries: Entry[] = [];
const byResource = new Map<ResourceLike, Entry>();
for (const [name, resource] of Object.entries(contracts)) {
  if (resource instanceof ReadResource) {
    const entry = { name, resource, expression: `contracts[${q(name)}]` };
    entries.push(entry);
    byResource.set(resource, entry);
  }
}
for (let index = 0; index < entries.length; index++) {
  const parent = entries[index];
  for (const [name, field] of Object.entries(parent.resource.fields)) {
    if (field.kind !== "relation" || byResource.has(field.resource)) continue;
    const entry = {
      name: `NestedResource${entries.length}`,
      resource: field.resource,
      expression: `${parent.expression}.fields[${q(name)}].resource`,
    };
    entries.push(entry);
    byResource.set(field.resource, entry);
  }
}
const lines: string[] = [
  "/** Generated by harness/generate-controls.ts. */",
  'import * as contracts from "../../contracts/resources";',
  'import { schema } from "@n/adira.core.ts";',
  'import { operatorFor, type FilterDescriptors } from "../controls/filter-controls";',
  'import type { ColumnVisibility } from "../controls/table-controls";',
  'import { booleanParser, enumParser, listParser, nonNullable, numberParser, stringParser } from "../controls/input-controls";',
];
let customImport = false;
function input(
  entry: Entry,
  field: string,
  definition: ScalarDefinition,
  expression: string,
  operator: string,
): string {
  if (operator === "$startsWith" || operator === "$contains")
    return "stringParser(schema.string())";
  const native = definition.value.native;
  if (!native) {
    customImport = true;
    return `customParsers[${q(entry.name)}][${q(field)}][${q(operator)}]`;
  }
  const comparison = ["$gt", "$gte", "$lt", "$lte"].includes(operator);
  const value = comparison
    ? `nonNullable(${expression}.value)`
    : `${expression}.value`;
  const factory =
    native.type === "number"
      ? "numberParser"
      : native.type === "boolean"
        ? "booleanParser"
        : native.type === "enum"
          ? "enumParser"
          : "stringParser";
  const scalar = `${factory}(${value})`;
  return operator === "$in" || operator === "$nin"
    ? `listParser(${scalar})`
    : scalar;
}
const dashboard: string[] = [
  "/** Generated dashboard conveniences. Public parsers in controls.ts do not depend on this module. */",
  'import type * as contracts from "../../contracts/resources";',
  'import * as inputs from "./controls";',
  'import { defineFilterEditors, ruleFor, type FilterChoice, type FilterRuleFactories } from "../controls/filter-state";',
];
for (const entry of entries) {
  const { name, resource, expression } = entry;
  const alias = `R_${name}`;
  const filters = `${name}Filters`,
    rules = `${name}FilterRules`,
    choices = `${name}Choices`,
    editors = `${name}FilterEditors`;
  const scalars = Object.entries(resource.fields).filter(
    ([, field]) => field.kind === "scalar",
  );
  const fields = [
    ...Object.entries(resource.fields).flatMap(([key, field]) =>
      field.kind === "scalar" && field.operators.length
        ? [
            {
              key,
              field,
              predicate: false,
              expression: `${expression}.fields[${q(key)}]`,
            },
          ]
        : [],
    ),
    ...Object.entries(resource.predicates).map(([key, field]) => ({
      key,
      field,
      predicate: true,
      expression: `${expression}.predicates[${q(key)}]`,
    })),
  ];
  lines.push(
    `type ${alias} = typeof ${expression};`,
    `export const ${name}Columns = { ${scalars.map(([key]) => `${q(key)}: false`).join(", ")} } satisfies ColumnVisibility<${alias}>;`,
    `const ${name}Operator = operatorFor<${alias}>();`,
    `export const ${filters} = {`,
  );
  dashboard.push(
    `type ${alias} = typeof ${expression};`,
    `const ${name}Rule = ruleFor<${alias}>();`,
    `export const ${rules} = {`,
  );
  for (const item of fields) {
    lines.push(`${q(item.key)}: {`);
    dashboard.push(`${q(item.key)}: {`);
    for (const operator of item.field.operators) {
      lines.push(
        `${q(operator)}: ${name}Operator({ field: ${q(item.key)}, operator: ${q(operator)},`,
        `input: ${input(entry, item.key, item.field, item.expression, operator)}, }),`,
      );
      dashboard.push(
        `${q(operator)}: ${name}Rule(inputs.${filters}[${q(item.key)}][${q(operator)}],`,
        `value => ({ ${q(item.key)}: { ${q(operator)}: value } })),`,
      );
    }
    lines.push("},");
    dashboard.push("},");
  }
  lines.push(`} satisfies FilterDescriptors<${alias}>;`);
  dashboard.push(
    `} satisfies FilterRuleFactories<${alias}>;`,
    `const ${choices} = {`,
  );
  for (const item of fields) {
    const firstOp = item.field.operators[0];
    dashboard.push(
      `${q(item.key)}: { id: ${q(item.key)}, field: ${q(item.key)}, predicate: ${item.predicate},`,
      `create: () => ${rules}[${q(item.key)}][${q(firstOp)}].create(), operators: [`,
    );
    for (const op of item.field.operators)
      dashboard.push(
        `{ id: ${q(op)}, create: () => ${rules}[${q(item.key)}][${q(op)}].create() },`,
      );
    dashboard.push("]},");
  }
  dashboard.push(
    `} satisfies { [K in keyof FilterRuleFactories<${alias}>]: FilterChoice<${alias}> };`,
    `export const ${editors} = defineFilterEditors<${alias}>({`,
    `fields: Object.values(${choices}),`,
    "combine: { and: children => ({ $and: children }), or: children => ({ $or: children }), not: child => ({ $not: child }) },",
    "});",
  );
}
if (customImport)
  lines.splice(
    5,
    0,
    'import { customParsers } from "../controls/control-overrides";',
  );
async function writeAdapters() {
  for (const [filename, source] of [
    ["controls.ts", lines],
    ["dashboard-filters.ts", dashboard],
  ] as const) {
    const destination = resolve(
      __dirname,
      "../../frontend/generated",
      filename,
    );
    const output = await format(source.join("\n") + "\n", {
      parser: "typescript",
    });
    if (process.argv.includes("--check")) {
      if (
        !existsSync(destination) ||
        readFileSync(destination, "utf8") !== output
      )
        throw new Error(
          "Generated controls are stale. Run npm run generate:controls -w examples/stress.",
        );
    } else {
      mkdirSync(dirname(destination), { recursive: true });
      if (
        !existsSync(destination) ||
        readFileSync(destination, "utf8") !== output
      )
        writeFileSync(destination, output);
    }
  }
  console.log(
    `${process.argv.includes("--check") ? "Checked" : "Generated"} ${entries.length} headless parser sets and dashboard adapters.`,
  );
}
writeAdapters().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
